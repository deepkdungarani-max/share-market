def seed(conn) -> int:
    """Queue every syllabus topic not yet known; mark one already known as part of the syllabus. Returns how
    many were added."""
    added = 0
    for level, _, _, topics in LEVELS:
        for title, why in topics:
            key = topic_key(title)
            cur = conn.execute("INSERT OR IGNORE INTO topics (title, key, why, depth, priority, syllabus) "
                               "VALUES (?, ?, ?, 0, ?, ?)", (title, key, why, PRIORITY, level))
            if cur.rowcount:
                added += 1
            else:
                conn.execute("UPDATE topics SET syllabus = ?, priority = MAX(priority, ?) "
                             "WHERE key = ? AND syllabus IS NULL", (level, PRIORITY, key))
    conn.commit()
    return added


def view(conn) -> list[dict]:
    """Each level with its books, how many of its topics are learned, and every topic with its status."""
    rows = conn.execute("SELECT id, title, status, syllabus FROM topics WHERE syllabus IS NOT NULL "
                        "ORDER BY syllabus, id").fetchall()
    out = []
    for level, name, books, _ in LEVELS:
        topics = [{"id": i, "title": t, "status": s} for i, t, s, lv in rows if lv == level]
        out.append({"level": level, "name": name, "books": books, "total": len(topics),
                    "done": sum(t["status"] == "done" for t in topics), "topics": topics})
    return out
